export function findAppliance(id: string): Appliance | undefined {
  return APPLIANCES.find((a) => a.id === id);
}

export function findFault(id: string): Fault | undefined {
  return FAULTS.find((f) => f.id === id);
}

export function applianceGroups(): Record<string, Appliance[]> {
  const groups: Record<string, Appliance[]> = {};
  for (const appliance of APPLIANCES) {
    (groups[appliance.group] ??= []).push(appliance);
  }
  return groups;
}